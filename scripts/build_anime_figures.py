def esc(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def emit_fig(t):
    aid, name, dynasty, ennea, title, weights, traits, analysis, parallels = t
    w = ", ".join(f"{k}: {v}" for k, v in weights.items())
    tr = ", ".join(f'"{esc(x)}"' for x in traits)
    return f"""      {{
        id: "{aid}",
        name: "{esc(name)}",
        dynasty: "{esc(dynasty)}",
        enneagram: "{ennea}",
        title: "{esc(title)}",
        weights: {{ {w} }},
        traits: [{tr}],
        analysis: "{esc(analysis)}",
        parallels: "{esc(parallels)}",
      }}"""


def main():
    lines = ["  const FIGURES = {"]
    for i, (code, figs) in enumerate(RAW.items()):
        lines.append(f"    {code}: [")
        for j, fig in enumerate(figs):
            lines.append(emit_fig(fig) + ("," if j < len(figs) - 1 else ""))
        lines.append("    ]" + ("," if i < len(RAW) - 1 else ""))
    lines.append("  };")
    out = Path(__file__).resolve().parents[1] / "scripts" / "_figures_anime.js"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n = sum(len(v) for v in RAW.values())
    enneas = {}
    for code, figs in RAW.items():
        enneas[code] = sorted({f[3] for f in figs})
    print("figures", n)
    for code, es in enneas.items():
        print(code, len(RAW[code]), ",".join(es))
    # uniqueness
    ids = [f[0] for figs in RAW.values() for f in figs]
    assert len(ids) == len(set(ids)), [x for x in ids if ids.count(x) > 1]


if __name__ == "__main__":
    main()
